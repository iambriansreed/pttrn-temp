/**
 * Generates the Flag data files in packages/react/src/components/Flag.
 *
 * At run time the script downloads the 32px flag sprite (PNG) and its ISO 3166-1 alpha-2 stylesheet from
 * https://github.com/lafeber/world-flags-sprite (MIT, see attribution.md). It reads each flag's sprite offset from the
 * stylesheet and writes two files: codes.ts, the list of flag codes, and one flag.scss shared by every flag. The
 * stylesheet embeds the sprite as a data URI, so the component needs no separate asset, and holds each flag's sprite
 * offset.
 *
 * The country codes are ISO 3166-1 alpha-2: http://en.wikipedia.org/wiki/ISO_3166-1_alpha-2
 *
 * Flag.tsx, FlagExample.tsx, index.tsx and package.json are maintained by hand and never touched by this script.
 *
 * Do not edit codes.ts or flag.scss by hand, re-run this script instead:
 *
 * $ npx tsx packages/react/.scripts/lib/generateFlagComponent.ts
 */

import { execSync } from 'child_process';
import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const SOURCE_URL = 'https://raw.githubusercontent.com/lafeber/world-flags-sprite/master';
const SPRITE_URL = `${SOURCE_URL}/images/flags32.png`;
const CSS_URL = `${SOURCE_URL}/stylesheets/flags32-iso-3166-1-alpha-2.css`;

const PACKAGE_DIR = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const FLAG_DIR = path.join(PACKAGE_DIR, 'src/components/Flag');
const SCRIPT_PATH = 'packages/react/.scripts/lib/generateFlagComponent.ts';

(async () => {
    const [sprite, css] = await Promise.all([download(SPRITE_URL), download(CSS_URL)]);

    const offsets = parseOffsets(css.toString('utf-8'));

    await fs.mkdir(FLAG_DIR, { recursive: true });

    const codesFilePath = path.join(FLAG_DIR, 'codes.ts');
    const stylesFilePath = path.join(FLAG_DIR, 'flag.scss');
    await fs.writeFile(codesFilePath, generateCodesFile(Object.keys(offsets)));
    await fs.writeFile(stylesFilePath, generateStylesFile(sprite.toString('base64'), offsets));

    try {
        execSync(`npx prettier --write ${codesFilePath} ${stylesFilePath}`, { cwd: PACKAGE_DIR, stdio: 'ignore' });
    } catch {
        console.warn('Prettier failed, the generated file was left unformatted.');
    }

    console.info(`${Object.keys(offsets).length} flags written to ${codesFilePath} and ${stylesFilePath}`);
})().catch((error) => {
    console.error(error);
    process.exit(1);
});

async function download(url: string) {
    const response = await fetch(url);

    if (!response.ok) throw new Error(`Failed to download ${url}: ${response.status} ${response.statusText}`);

    return Buffer.from(await response.arrayBuffer());
}

/** Maps each flag name to its vertical offset in the sprite, in cells of 32px. */
function parseOffsets(css: string) {
    const offsets: Record<string, number> = {};

    for (const [, selectors, y] of css.matchAll(/([^{}]+)\{background-position:0 (-?\d+)(?:px)?;\}/g)) {
        for (const selector of selectors.split(',')) {
            const name = selector.trim().replace(/^\.f32 \./, '');

            if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) offsets[name] = Math.abs(Number(y)) / 32;
        }
    }

    if (!Object.keys(offsets).length) throw new Error('No flags found in the downloaded stylesheet.');

    return Object.fromEntries(Object.entries(offsets).sort(([a], [b]) => a.localeCompare(b)));
}

function generateStylesFile(spriteBase64: string, offsets: Record<string, number>) {
    const rules = Object.entries(offsets)
        .map(([code, offset]) => `[data-pttrn='flag'][data-flag='${code}'] { --flag-offset: ${offset}; }`)
        .join('\n');

    return `/* stylelint-disable */
// DO NOT EDIT. This file is generated by ${SCRIPT_PATH}
// Flag sprite and offsets: https://github.com/lafeber/world-flags-sprite

// --flag-size is set by the component, --flag-offset is the flag's row in the sprite.
[data-pttrn='flag'] {
    --flag-size: 32;
    --flag-offset: 0;

    display: inline-block;
    flex-shrink: 0;
    width: calc(var(--flag-size) * 1px);
    height: calc(var(--flag-size) * 1px);
    background-image: url('data:image/png;base64,${spriteBase64}');
    background-repeat: no-repeat;
    background-size: calc(var(--flag-size) * 1px) auto;
    background-position: 0 calc(var(--flag-offset) * var(--flag-size) * -1px);
}

${rules}
`;
}

function generateCodesFile(codes: string[]) {
    return `// DO NOT EDIT. This file is generated by ${SCRIPT_PATH}
// Flag sprite and offsets: https://github.com/lafeber/world-flags-sprite

export const CODES = ${JSON.stringify(codes)} as const;
`;
}
