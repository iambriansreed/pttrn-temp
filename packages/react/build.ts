/**
 * Build script for pttrn UI
 *
 * This script compiles TypeScript files, processes CSS files, and prepares the final distribution package.
 *
 * It performs the following tasks:
 *
 * 1. Compiles TypeScript files using `tsc`
 * 2. Processes SASS files using `npm run sass`.
 * 3. Copies the font, token and theme stylesheets from `@ptrn/styles` into dist/styles.
 * 4. Creates importable CSS files for them.
 * 5. Creates importable CSS files for each component.
 * 6. Translates import paths from aliases to relative paths.
 * 7. Moves the temporary build directory to the final distribution directory.
 * 8. Updates the package exports to include component directories.
 *
 * $ npx tsx build.ts
 */
import child_process from 'child_process';
import fs from 'fs';
import path from 'path';
import util from 'util';

// eslint-disable-next-line no-restricted-imports -- a repository-level build helper, outside this package
import { addJsExtensions } from '../../scripts/add-js-extensions.mjs';
import packageData from './package.json';

import { compilerOptions } from './tsconfig.json';

const exec = util.promisify(child_process.exec);
const writeFile = util.promisify(fs.writeFile);
const readDir = util.promisify(fs.readdir);
const readFile = (filePath: string) => util.promisify(fs.readFile)(filePath, 'utf-8');

const STYLES_SOURCE_DIR = path.dirname(import.meta.resolve('@ptrn/styles/package.json').split('file:')[1]);

const distPath = path.resolve('./dist');
const distStylesPath = path.resolve('./dist/styles');

const RESET = '\x1b[0m';
const GREEN = '\x1b[32m';
const BLUE = '\x1b[34m';

async function main() {
    const startTime = Date.now();

    console.log(`${BLUE}Building pttrn UI...${RESET}`);

    await exec(`rm -rf ${distPath} && mkdir -p ${distStylesPath}`);

    await exec('tsc --project ./tsconfig.build.json && npm run sass');

    // copy the token and theme stylesheets from @ptrn/styles into dist/styles. Not the fonts: their @import of the
    // @fontsource packages only resolves through the app's bundler, never from a runtime-injected <style>.
    await exec(`cp ${path.resolve(STYLES_SOURCE_DIR, 'tokens.css')} ${distStylesPath}/`);
    await exec(`cp -R ${path.resolve(STYLES_SOURCE_DIR, 'themes')} ${distStylesPath}/`);

    await writeComponentsStylesheet();

    await Promise.all([fileProcessing(), componentExports()]);

    // Node's ESM resolver needs explicit extensions; tsc leaves relative specifiers as written.
    const rewritten = await addJsExtensions(distPath);
    console.log(`Added explicit .js extensions in ${rewritten} files`);

    // copy dist to dist

    const endTime = Date.now();

    console.log(`${GREEN}pttrn UI build completed successfully (${(endTime - startTime) / 1000}s)${RESET}`);
}

main();

/**
 * Concatenates the base styles and every component stylesheet into `dist/styles/components.css`. Components inject
 * their own CSS when imported; this file is for consumers who load CSS through their own pipeline instead (server
 * rendering, a strict Content Security Policy) and opt out of injection with `data-pttrn-styles="external"` on
 * `<html>`.
 */
async function writeComponentsStylesheet() {
    const cssFiles = (await readDir(distPath, { encoding: 'utf-8', recursive: true, withFileTypes: true }))
        .filter(
            (dirent) =>
                dirent.isFile() && dirent.name.endsWith('.css') && !dirent.parentPath.startsWith(distStylesPath),
        )
        .map((dirent) => path.resolve(dirent.parentPath, dirent.name))
        .sort((a, b) =>
            a.includes('/styles/base.css') ? -1 : b.includes('/styles/base.css') ? 1 : a.localeCompare(b),
        );
    const css = await Promise.all(
        cssFiles.map(async (file) => `/* ${path.relative(distPath, file)} */\n${await readFile(file)}`),
    );
    await writeFile(
        path.resolve(distStylesPath, 'components.css'),
        `/* @ptrn/react ${packageData.version}: base styles and every component stylesheet. Generated by the build. */\n${css.join('\n')}`,
        'utf-8',
    );
}

async function fileProcessing() {
    const allFiles = await readDir(distPath, { encoding: 'utf-8', recursive: true, withFileTypes: true });

    await Promise.all(
        allFiles.map(async (dirent) => {
            if (!dirent.isFile()) return;

            const filePath = path.resolve(dirent.parentPath, dirent.name);

            // make importable .css files
            if (filePath.endsWith('.css')) {
                return createImportableCss(await readFile(filePath), filePath.replace(/\.css$/, '.css.js'));
            }

            // fix import paths in .js files and in the declaration files consumers' type checkers read
            if (filePath.endsWith('.js') || filePath.endsWith('.d.ts')) {
                let newFileContent = await readFile(filePath);

                if (filePath.endsWith('.js')) {
                    // fix import paths for styles
                    newFileContent = cssImportsInjected(newFileContent);

                    // fix import paths for '@ptrn/styles. The css files are now in the dist/styles directory.
                    newFileContent = newFileContent.replaceAll("import '@ptrn/styles/", "import '-/styles/");
                }

                // translate alias imports to relative paths
                newFileContent = aliasToRelative(newFileContent, filePath);

                return writeFile(filePath, newFileContent, 'utf-8');
            }
        }),
    );
}

// Create a mapping of TypeScript alias paths to relative paths
const tsConfigPathsToRelative = Object.fromEntries(
    Object.entries(compilerOptions.paths).map(([aliasPath, relativePaths]) => {
        // Convert the alias path to a relative path
        const relativePath = relativePaths[0].replace(/\/\*$/, '/');
        return [
            aliasPath.replace(/\/\*$/, '/'),
            path.resolve(compilerOptions.baseUrl ?? '.', relativePath.replace('/src/', '/dist/')),
        ];
    }),
);

/**
 * This function converts TypeScript alias paths to relative paths based on the current file's location. It reads the
 * tsConfigPathsToRelative object to find the corresponding relative path for each alias import in the file content.
 */
function aliasToRelative(fileContent: string, filePath: string) {
    const aliasImportMatches = fileContent.matchAll(
        new RegExp(
            `((?:import|export) [^'\\n]*?|import\\()'(${Object.keys(tsConfigPathsToRelative).join('|')})([^']+)'(;?)`,
            'g',
        ),
    );

    for (const match of aliasImportMatches) {
        const [fullMatch, lead, aliasPathMatched, actualImportedFile, semicolon] = match;

        const relativePath = tsConfigPathsToRelative[aliasPathMatched] || '';
        const relativeFilePath =
            path.relative(path.dirname(filePath), path.resolve(relativePath, actualImportedFile)) || '.';
        const newImport = `${lead}'${relativeFilePath}'${semicolon}`;

        fileContent = fileContent.replace(fullMatch, newImport);
    }

    return fileContent;
}

function cssImportsInjected(fileContent: string) {
    return fileContent.replace(/import ['"]([^'"]+\/)?([^.]+)\.(s?css)['"];?/g, (_match, importPath = '', name) => {
        const nextImportPath = importPath || '';
        return `import '${nextImportPath}${name}.css.js';`;
    });
}

type ExportEntry = string | { types: string; default: string };

/** An export entry for a built module: the `.js` and, when the build produced one, its `.d.ts`. */
function moduleEntry(jsPath: string): ExportEntry {
    const typesPath = jsPath.replace(/\.js$/, '.d.ts');
    return fs.existsSync(path.resolve(typesPath)) ? { types: typesPath, default: jsPath } : jsPath;
}

async function componentExports() {
    const nextExports: Record<string, ExportEntry> = {
        ...(packageData['static-exports'] as Record<string, ExportEntry>),
    };

    await Promise.all(
        (await readDir(path.resolve('./dist/components'), { withFileTypes: true }))
            //
            .map(async (dirent) => {
                //
                if (!dirent.isDirectory() || dirent.name.startsWith('.')) return;

                nextExports[`./${dirent.name}`] = moduleEntry(`./dist/components/${dirent.name}/index.js`);
                nextExports[`./${dirent.name}/*`] = {
                    types: `./dist/components/${dirent.name}/*.d.ts`,
                    default: `./dist/components/${dirent.name}/*.js`,
                };

                const files = await Promise.all(
                    (await readDir(`${'./dist/components'}/${dirent.name}`))
                        .filter((file) => file.endsWith('.js') || file.endsWith('.ts'))
                        .map(async (file) => ({
                            filePath: `${'./dist/components'}/${dirent.name}/${file}`,
                            content: await readFile(`${'./dist/components'}/${dirent.name}/${file}`),
                        })),
                );

                // look for files in each folder with the @export tag and add them to nextExports
                files.forEach(({ filePath, content }) => {
                    const nameMatch = content.match(/ \* @name\W([^\W]+)/)?.[1];
                    const exportMatch = content.match(/ \* @export/);

                    if (exportMatch && nameMatch) {
                        nextExports[`./${nameMatch}`] = moduleEntry(filePath);
                    }
                });
            }),
    );

    (packageData.exports as Record<string, ExportEntry>) = Object.fromEntries(
        Object.entries(nextExports).sort(([aKey], [bKey]) => aKey.localeCompare(bKey)),
    );

    return writeFile(path.resolve('./package.json'), `${JSON.stringify(packageData, null, 4)}\n`, 'utf-8');
}

/**
 * Writes a `.css.js` module that appends the stylesheet to `<head>` once. The id, derived from the file's path in dist,
 * stops the same stylesheet being appended twice when two bundles load it, and the `document` guard keeps the import
 * harmless during server rendering. The CSS is embedded as a JSON string, so backticks, backslashes and `${` in the
 * stylesheet cannot break the module.
 */
async function createImportableCss(cssContent: string, destPath: string) {
    // The injected <style> is resolved by the browser against the page, so an @import of a package or a relative file
    // would 404 at runtime (that is how the fonts once went missing). Only absolute URLs can be injected.
    const unresolvable = [...cssContent.matchAll(/@import\s+(?:url\()?\s*['"]?([^'")\s;]+)/g)]
        .map((match) => match[1])
        .filter((target) => !/^https?:\/\//.test(target));
    if (unresolvable.length) {
        throw new Error(
            `${path.relative(distPath, destPath)} would inject @import ${unresolvable.join(', ')}, which a browser cannot resolve from a runtime <style>. Import that stylesheet through the app's bundler instead.`,
        );
    }
    const id = JSON.stringify(
        path
            .relative(distPath, destPath)
            .replace(/\.css\.js$/, '')
            .replace(/[\\/]/g, '-'),
    );
    return await writeFile(
        destPath,
        `/** Generated by the build script. Do not edit. */
if (typeof document !== 'undefined' && document.documentElement.dataset.pttrnStyles !== 'external' && !document.querySelector(\`style[data-pttrn-style=${id}]\`)) {
    const style = document.createElement('style');
    style.dataset.pttrnStyle = ${id};
    style.appendChild(document.createTextNode(${JSON.stringify(cssContent)}));
    document.head.appendChild(style);
}
`,
    );
}
