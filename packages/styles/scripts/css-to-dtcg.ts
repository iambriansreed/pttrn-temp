/**
 * One-time import: turns the stylesheets the Figma plugin exported (`tokens.css`, `themes/*.css`) into the DTCG token
 * source under `tokens/`. Every custom property becomes a token with its Figma name, CSS name, type and value; every
 * `[data-*]` mode block becomes a mode of its collection; the theme files become the modes of the theme collection.
 * `npm run build` in this package then regenerates the same stylesheets from that source.
 *
 * Npx tsx scripts/css-to-dtcg.ts [--from <dir with tokens.css and themes/>] [--to tokens]
 *
 * Once the plugin exports DTCG files itself this script is only needed to import an older CSS-only export.
 */
import fs from 'node:fs';
import path from 'node:path';

import {
    Collection,
    Manifest,
    Prop,
    TokenValue,
    rgbFromCss,
    shadowFromCss,
    slug,
    tokenPath,
    writeTokenFiles,
} from './dtcg.js';

const args = process.argv.slice(2);
const option = (name: string, fallback: string) => {
    const index = args.indexOf(name);
    return index >= 0 ? args[index + 1] : fallback;
};
const packageRoot = path.resolve(import.meta.dirname, '..');
const from = path.resolve(packageRoot, option('--from', '.'));
const to = path.resolve(packageRoot, option('--to', 'tokens'));

type Block = { selector: string; items: { group: string; comment: string; name: string; value: string }[] };

/** Splits a stylesheet into its header comment and its blocks of commented `--name: value;` declarations. */
function parseStylesheet(css: string): { header: string[]; blocks: Block[] } {
    const headerMatch = css.match(/^\/\*\n([\s\S]*?)\n \*\//);
    const header = headerMatch ? headerMatch[1].split('\n').map((line) => line.replace(/^ \*\s?/, '')) : [];

    const blocks: Block[] = [];
    const blockPattern = /^([^\s/][^{\n]*) \{\n([\s\S]*?)\n\}/gm;
    for (const match of css.matchAll(blockPattern)) {
        const [, selector, body] = match;
        const lines = body.split('\n');
        const items: Block['items'] = [];
        let group = '';
        let comment: string | null = null;
        for (let i = 0; i < lines.length; i++) {
            const line = lines[i].trim();
            if (!line) continue;
            const commentMatch = line.match(/^\/\* (.*) \*\/$/);
            if (commentMatch) {
                const next = (lines[i + 1] ?? '').trim();
                if (next.startsWith('--')) comment = commentMatch[1];
                else group = commentMatch[1];
                continue;
            }
            const declaration = line.match(/^(--[^:]+): (.*);$/);
            if (!declaration) throw new Error(`unexpected line in ${selector}: ${line}`);
            items.push({ group, comment: comment ?? declaration[1], name: declaration[1], value: declaration[2] });
            comment = null;
        }
        blocks.push({ selector, items });
    }
    return { header, blocks };
}

const tokensCss = fs.readFileSync(path.join(from, 'tokens.css'), 'utf8');
const { header, blocks } = parseStylesheet(tokensCss);

// Provenance from the header.
const figmaFile = header.find((line) => line.startsWith('Figma file: '))?.slice('Figma file: '.length) ?? '';
const exportedAt =
    header
        .find((line) => line.startsWith('Generated by pttrn Export Tokens on '))
        ?.replace(/^Generated by pttrn Export Tokens on /, '') ?? '';

// The mode index: `[data-attr]   default (default), other, ...` in the order the plugin listed them.
const modeIndex: { attribute: string; modes: string[]; defaultMode: string }[] = [];
for (const line of header) {
    const match = line.match(/^\s*\[(data-[a-z0-9-]+)\]\s+(.*)$/);
    if (!match) continue;
    const modes = match[2].split(',').map((mode) => mode.trim().replace(' (default)', ''));
    const defaultMode = match[2]
        .split(',')
        .map((mode) => mode.trim())
        .find((mode) => mode.endsWith(' (default)'))
        ?.replace(' (default)', '');
    modeIndex.push({ attribute: match[1], modes, defaultMode: defaultMode ?? modes[0] });
}

const collections: Collection[] = [];
const props = new Map<string, Prop>();
const collectionOf = new Map<string, Collection>();
const usedSlugs = new Set<string>();

function newCollection(name: string, extra: Partial<Collection> = {}): Collection {
    const base = slug(name) || 'collection';
    let s = base;
    for (let i = 2; usedSlugs.has(s); i++) s = `${base}-${i}`;
    usedSlugs.add(s);
    const collection: Collection = { name, slug: s, kind: 'variables', ...extra };
    collections.push(collection);
    return collection;
}

function addProp(collection: Collection, item: Block['items'][number]) {
    if (props.has(item.name)) throw new Error(`${item.name} declared twice as a default`);
    const prop: Prop = {
        collection: collection.slug,
        group: item.group,
        comment: item.comment,
        name: item.name,
        def: item.value,
        modes: {},
    };
    props.set(item.name, prop);
    collectionOf.set(item.name, collection);
}

// 1. The :root block: single-mode collections (and style groups), in order. A name that comes back after another
//    group is a second collection with the same name (the plugin prefixes its CSS names with the group).
const root = blocks.find((block) => block.selector === ':root');
if (!root) throw new Error('tokens.css has no :root block');
let current: Collection | null = null;
const prefixed = (name: string, group: string) => name.startsWith(`--${slug(group)}-`);
for (const item of root.items) {
    if (!current || current.name !== item.group) {
        // Variables fetched on demand (aliases into a library) register while the local ones convert, so one
        // collection can appear in several runs. A later claimant of a clashing name gets its group as a prefix,
        // which tells those runs apart from a local collection with the same name.
        const previous = [...collections].reverse().find((c) => c.name === item.group && c.kind === 'variables');
        const previousPrefixed =
            previous &&
            [...props.values()]
                .filter((p) => p.collection === previous.slug)
                .every((p) => prefixed(p.name, item.group));
        if (previous && previousPrefixed && prefixed(item.name, item.group)) {
            current = previous;
        } else {
            const kind = /styles$/i.test(item.group) ? 'styles' : 'variables';
            current = newCollection(item.group, { kind });
        }
    }
    addProp(current, item);
}

// 2. Multi-mode collections from `:root, [data-attr="default"]` blocks and their mode blocks.
const byAttribute = new Map<string, Collection>();
for (const block of blocks) {
    const own = block.selector.match(/^:root, \[(data-[a-z0-9-]+)="([^"]+)"\]$/);
    if (!own) continue;
    const [, attribute, defaultMode] = own;
    const index = modeIndex.find((entry) => entry.attribute === attribute);
    if (!index) throw new Error(`${attribute} is not in the header's mode index`);
    const name = block.items[0]?.group ?? attribute;
    const collection = newCollection(name, { attribute, modes: index.modes, defaultMode });
    byAttribute.set(attribute, collection);
    for (const item of block.items) addProp(collection, item);
}
for (const block of blocks) {
    const mode = block.selector.match(/^\[(data-[a-z0-9-]+)="([^"]+)"\]$/);
    if (!mode) continue;
    const [, attribute, key] = mode;
    const collection = byAttribute.get(attribute);
    if (!collection) throw new Error(`mode block for unknown ${attribute}`);
    if (key === collection.defaultMode) continue; // the "outside dependents" block, derived at build time
    for (const item of block.items) {
        const prop = props.get(item.name);
        // Dependents from other collections are redeclared here; only this collection's own tokens carry modes.
        if (!prop || prop.collection !== collection.slug) continue;
        if (item.value !== prop.def) prop.modes[key] = item.value;
    }
}

// 3. The theme collection: one complete file per mode under themes/.
const themeIndex = modeIndex.find((entry) => !byAttribute.has(entry.attribute));
if (themeIndex) {
    const themesDir = path.join(from, 'themes');
    const files = themeIndex.modes.map((mode) => ({
        mode,
        css: fs.readFileSync(path.join(themesDir, `${mode}.css`), 'utf8'),
    }));
    const defaultFile = files.find(({ css }) => css.includes('(its default), complete.')) ?? files[0];
    const parsed = files.map(({ mode, css }) => ({ mode, ...parseStylesheet(css) }));
    const defaultBlock = parsed.find((file) => file.mode === defaultFile.mode)!.blocks[0];
    const name = defaultBlock.items[0]?.group ?? 'Theme';
    const collection = newCollection(name, {
        attribute: themeIndex.attribute,
        modes: themeIndex.modes,
        defaultMode: defaultFile.mode,
        theme: true,
    });
    for (const item of defaultBlock.items) if (item.group === name) addProp(collection, item);
    for (const file of parsed) {
        if (file.mode === defaultFile.mode) continue;
        for (const item of file.blocks[0].items) {
            const prop = props.get(item.name);
            if (!prop || prop.collection !== collection.slug) continue;
            if (item.value !== prop.def) prop.modes[file.mode] = item.value;
        }
    }
    // The plugin lists the theme first in its mode index; keep that order in the manifest.
    collections.splice(collections.indexOf(collection), 1);
    const firstMulti = collections.findIndex((c) => c.attribute);
    collections.splice(firstMulti < 0 ? collections.length : firstMulti, 0, collection);
}

// 4. Values: aliases need the token path of their target, so paths come first.
const cssToPath = new Map<string, string>();
for (const prop of props.values()) cssToPath.set(prop.name, tokenPath(collectionOf.get(prop.name)!, prop));

const warnings: string[] = [];
function toValue(text: string, prop: Prop): TokenValue {
    const alias = text.match(/^var\((--[A-Za-z0-9_-]+)\)$/);
    if (alias) {
        const target = cssToPath.get(alias[1]);
        if (!target) throw new Error(`${prop.name} references ${alias[1]}, which is not a token`);
        return { $value: `{${target}}` };
    }
    const color = rgbFromCss(text);
    if (color) return { $type: 'color', $value: color };
    const px = text.match(/^(-?\d*\.?\d+)px$/);
    if (px) return { $type: 'dimension', $value: { value: Number(px[1]), unit: 'px' } };
    if (/^-?\d*\.?\d+$/.test(text)) return { $type: 'number', $value: Number(text) };
    const quoted = text.match(/^"(.*)"$/);
    if (quoted) {
        // A variable named "font-family/sans" or a text style's "(font family)" property, as in the plugin.
        const about = (what: string) => new RegExp(`font[-\\s/]?${what}`, 'i').test(`${prop.comment} ${prop.name}`);
        if (about('family')) return { $type: 'fontFamily', $value: quoted[1] };
        if (about('weight')) return { $type: 'fontWeight', $value: quoted[1] };
        // No DTCG type fits a plain string (a size name, a focus style); `string` is pttrn's extension.
        warnings.push(`${prop.name} is a plain string ("${quoted[1]}"), exported with the non-standard type string`);
        return { $type: 'string', $value: quoted[1] };
    }
    const shadow = shadowFromCss(text);
    if (shadow) return { $type: 'shadow', $value: shadow };
    throw new Error(`${prop.name}: cannot type the value ${text}`);
}

const manifest: Manifest = {
    source: {
        figmaFile,
        exportedAt,
        exporter: 'pttrn Export Tokens',
        importedBy: 'scripts/css-to-dtcg.ts from tokens.css and themes/*.css',
    },
    collections,
};

fs.rmSync(to, { recursive: true, force: true });
const written = writeTokenFiles(to, manifest, [...props.values()], toValue);

console.log(
    `Imported ${props.size} tokens from ${collections.length} collections into ${path.relative(packageRoot, to)}/`,
);
for (const collection of collections) {
    const count = [...props.values()].filter((prop) => prop.collection === collection.slug).length;
    console.log(
        `  ${collection.name.padEnd(22)} ${String(count).padStart(5)} tokens${collection.modes ? `  modes: ${collection.modes.join(', ')}` : ''}`,
    );
}
console.log(`${written} files written`);
if (warnings.length) console.warn(`\nNotes:\n  ${warnings.join('\n  ')}`);
